import 'package:uuid/uuid.dart';

const Uuid _uuid = Uuid();

/// 全局统一 ID 生成入口。
///
/// UUIDv7 时间有序 —— 这同时满足两个需求：
/// 1. 客户端离线也能生成全局唯一 id（同步的幂等键，见 `docs/sync_protocol.md` §二）
/// 2. 按 id 排序即近似按时间排序
///
/// ⚠️ **有序性是毫秒粒度的**：UUIDv7 的时间戳部分只有 48 位毫秒，
/// 因此**同一毫秒内生成的两个 id，顺序由随机尾巴决定，没有保证**
/// （实测：连续两次 `newId()` 的字典序可能反着）。
///
/// 这不影响任何正确性 —— `(created_at, id)` 仍是**确定的全序**，
/// 只是"同一毫秒内的插入顺序"不可依赖。`docs/data_model.md` §七 的
/// 客户端本地排序因此是可靠的，但**不要**把 id 当插入序号用。
String newId() => _uuid.v7();
