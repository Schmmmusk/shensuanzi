/// |---|---|
/// | `shensuanzi_core` | `syncFailureReason`（约束冲突 / 存储故障的中文结论） |
/// | `shensuanzi_host` | `SyncServer` 的 `rejected` reason |
/// | `shensuanzi_app` | 手册 / 移动引导 / 扫码错误 |
///
/// 它原先住在 `shensuanzi_app`，**只因为最初是从那里的 `manual_content.dart` 提取的** ——
/// 提取时没想清「这是 app 层规则还是项目级规则」。2026-10-09 消费点扩展到 core 的测试，
/// 正好把这个问题暴露出来，遂**归位**到最底层（`docs/reply_review.md` §CV·十三）。
///
/// ⚠️ **这不是边界变更**：没有引入任何**新的**跨包依赖
/// （core 不依赖 app，依赖方向始终是 app → core），只是把一个错放的常量归位。
///
/// ## 三层结构
///
/// 1. **本表** = **通用**开发术语 —— **所有**面向用户的文本都该过它；
/// 2. **模块级额外黑名单** = 模块特有的泄漏（表名 / 样例数据 / 插件类名 / 占位符）
///    —— 由该模块自己的断言补（`sync_failure_test` / `scan_error_test`）；
/// 3. 每个模块**两关都过**。
///
/// ⚠️ **表本身只是数据**：断言的调法由各包 `test/support/dev_terms.dart` 的薄 helper
