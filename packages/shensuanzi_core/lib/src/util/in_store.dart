/// **在店可售的唯一公式**（F17-b 甲，2026-10-26 用户裁定；
/// 2026-11-13 提案 61 从 `lib/src/ui/stock_page.dart` **整体搬迁**到 core）。
///
/// ```
/// 在店可售 = 账面库存 + 本地未同步影响 − 送货在途
/// ```
///
/// ## 为什么必须是**一个**函数
///
/// 这个数字的消费者已经**不止一个页面**：库存页的行内大字 / 负低库存判定 /
/// 列表排序 / **缺货榜**（提案 61 新增），概览页的缺货榜也要用它。
/// 各处若各算各的，就会出现用户无法理解的自相矛盾：
///
/// - 只改大字 ⇒ 大字写 34（低于安全库存 5）却仍是黑色、不报补货；
/// - 只改大字 ⇒ A 显示 3、B 显示 5，A 却排在 B 前面；
/// - 只改大字 ⇒ 大字 34、下方叠加行算出 36（两边算式不同）；
/// - 概览页与库存页各算一份 ⇒ 同一台手机上「库存页说缺货、概览页说不缺」。
///
/// 用户 `docs/reply.md` 的原话：「抽一个统一的函数，不要各处算 ——
/// 将来加字段或改公式时一定会漏」。
///
/// ## 为什么在 core 而不是 UI 层
///
/// 2026-11-13（提案 61 决策 61-⑦）把它定性为**业务领域规则**，不是 UI 规则：
/// 缺货榜的判定要跟着它走，而缺货榜的核心计算（`lib/src/ui/shortage.dart`）
/// 和将来可能加的库存预警都要调它。下沉之后 **UI 里不许再有一份** ——
/// `lib/src/ui/stock_page.dart` 那份已删除（不是 re-export）；
/// 机械保证见 `test/in_store_single_source_test.dart`。
///
/// ⚠️ 桌面端 `unsynced` 恒为 `0`（`stockDelta == null`）⇒ 这里与旧口径
/// `book - inTransit` **逐字相同**，桌面零回归。
library;

/// 在店可售 = 账面 + 本地未同步 − 送货在途。
///
/// 参数都是**最小单位**的数量（不是录入单位）。`unsynced` 是
/// `StockDelta.unsyncedDelta()` 给出的「本地已开、还没推给主机」的净影响。
int effectiveInStoreOf({
  required int book,
  required int unsynced,
  required int inTransit,
}) => book + unsynced - inTransit;
