/// **宽屏内容上限**（2026-11-24，界面精修批 B·1）。
///
/// ## 为什么在页面里做，不在壳里做
///
/// 2026-11-22 第一版加在 `app_shell` 的 `_content()` 上（一个 `ConstrainedBox`），
/// 用户在 1916×790 上立刻看出两个副作用：
///
/// 1. **滚轮在左右留白上完全不响应** —— 因为被缩窄的是**滚动视口本身**，
///    留白在视口之外；
/// 2. **页面标题被一起缩到中间**。
///
/// 所以宽度上限必须落在**页面内部**：滚动体保持全宽（滚轮处处有效），
/// 居中靠**视口内的横向内边距**；标题行不参与内边距（保持全宽）。
///
/// ## 规则（Q1 裁定）
///
/// | 可用宽 | 行为 |
/// |---|---|
/// | ≤ 1080 + 40 | 维持原边距 [base]（窄屏不浪费一个像素） |
/// | > 1080 + 40 | `(可用宽 − 1080) / 2`，即内容最宽 **1080**、左右等宽留白 |
///
/// 1080 是绝对上限：纯按 70% 算，32:9（约 2560 宽）上仍有 1792，
/// 一眼还是扫不过来。
library;

/// 内容区左右各自应该留出的横向内边距（逻辑像素）。
///
/// [available] 是**滚动视口**的宽度（`LayoutBuilder` 拿到的那一个），
/// [base] 是该页原本的左右内边距（多数页是 16 / 20）。
double pageContentInset(double available, {double base = 20}) {
  const double maxContent = 1080;
  if (available <= maxContent + base * 2) return base;
  return (available - maxContent) / 2;
}
